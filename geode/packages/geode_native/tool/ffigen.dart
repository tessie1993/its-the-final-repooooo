// Generates lib/src/geode_api.g.dart from core/api/geode_api.h, the C ABI of libgeode.so.
//
// Run from this package: dart run tool/ffigen.dart

import 'dart:io';

import 'package:ffigen/ffigen.dart';

void main() {
  final packageRoot = Platform.script.resolve('../');
  final header = packageRoot.resolve('../../core/api/geode_api.h');
  final ndkStandIns = packageRoot.resolve('tool/ffigen_include/');

  FfiGenerator(
    headers: Headers(
      entryPoints: [header],
      include: (uri) => uri == header,
      compilerOptions: ['-I${ndkStandIns.toFilePath()}'],
    ),
    functions: Functions(include: (decl) => decl.originalName.startsWith('geode_')),
    structs: Structs(include: (decl) => decl.originalName.startsWith('Geode') || decl.originalName.startsWith('geode_')),
    typedefs: Typedefs(include: (decl) => decl.originalName.startsWith('Geode') || decl.originalName.startsWith('geode_')),
    enums: Enums(include: (decl) => decl.originalName.startsWith('Geode'), silenceWarning: true),
    macros: Macros(include: (decl) => decl.originalName.startsWith('GEODE_') && decl.originalName != 'GEODE_API'),
    output: Output(
      dartFile: packageRoot.resolve('lib/src/geode_api.g.dart'),
      style: const DynamicLibraryBindings(wrapperName: 'GeodeApi'),
      format: true,
      preamble: '''
// Generated by package:ffigen from core/api/geode_api.h. Do not edit manually.
// To regenerate: dart run tool/ffigen.dart

// ignore_for_file: type=lint, unused_import, unused_element
''',
    ),
  ).generate();
}
